    category: str
    phrase: str
    expect: dict | None = None
    note: str = ""
    # Имена полей, которые должны попасть в IntentFacts.soft — то есть
    # модель должна заметить, что человек сам снял жёсткость с требования.
    expect_soft: frozenset = frozenset()


